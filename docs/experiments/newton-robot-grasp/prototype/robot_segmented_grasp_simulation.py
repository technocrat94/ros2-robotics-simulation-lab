#!/usr/bin/env python3
"""Visual contact lift-and-release test for the segmented strip."""

import argparse
import functools
import time

import newton
import numpy as np
import viser
from newton.viewer import ViewerViser

from robot_segmented_grasp_batch import (
    DT,
    FRAME_DT,
    SUBSTEPS,
    SHOW_COLLIDERS,
    COLLISION_SCOPE,
    DANCE_MODE,
    DANCE_DURATION,
    DANCE_SHOULDER_AMPLITUDE,
    DANCE_WRIST_AMPLITUDE,
    LIFT_DURATION,
    LIFT_HOLD_DURATION,
    TEST_DURATION,
    build_scene,
    grasp_region_links,
    robot_coordinates,
)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--start-delay", type=float, default=15.0)
    parser.add_argument("--port", type=int, default=8084)
    args = parser.parse_args()

    model, strip_links, _, _, _, active_colliders = build_scene()
    state_0, state_1 = model.state(), model.state()
    control = model.control()
    solver = newton.solvers.SolverXPBD(model, iterations=30)
    collision = newton.CollisionPipeline(model, rigid_contact_max=10000)
    contacts = collision.contacts()
    q, qd = model.joint_q.numpy(), model.joint_qd.numpy()
    robot_q, phase = robot_coordinates(0.0)
    q[:12] = robot_q
    model.joint_q.assign(q)
    newton.eval_fk(model, model.joint_q, model.joint_qd, state_0)
    initial_z = float(state_0.body_q.numpy()[strip_links, 2].mean())
    grip_links = grasp_region_links(strip_links)
    initial_grasp_z = float(state_0.body_q.numpy()[grip_links, 2].mean())
    previous_robot_q = robot_q.copy()

    server_class = viser.ViserServer
    viser.ViserServer = functools.partial(server_class, host="127.0.0.1")
    try:
        viewer = ViewerViser(
            port=args.port,
            label="UR5 + Robotiq Segmented-Strip Contact Test",
            share=False,
        )
    finally:
        viser.ViserServer = server_class
    viewer.set_model(model)
    server = viewer._server
    server.scene.set_up_direction("+z")
    server.initial_camera.position = (1.15, -1.35, 0.90)
    server.initial_camera.look_at = (0.42, 0.10, 0.32)
    server.initial_camera.up = (0.0, 0.0, 1.0)
    server.gui.add_markdown(
        "## Contact lift-and-release\n"
        "The robot follows prescribed joint motion. The strip remains dynamic; "
        "contact is generated by the enabled collision geometry, and the strip "
        "is not attached to the gripper.\n\n"
        f"Robot display: **{'collision geometry' if SHOW_COLLIDERS else 'visual geometry'}**"
        f"  \nCollision scope: **{COLLISION_SCOPE}**"
        f"  \nMotion mode: **{DANCE_MODE}**"
    )
    status = server.gui.add_markdown("Preparing...")

    wall_start = time.monotonic()
    sim_time = 0.0
    maximum_z = initial_z
    result_printed = False
    print(
        f"GRASP_VIEWER_READY start_delay={args.start_delay} port={args.port} "
        f"active_gripper_colliders={active_colliders}",
        flush=True,
    )

    try:
        while viewer.is_running():
            remaining = max(0.0, args.start_delay - (time.monotonic() - wall_start))
            if remaining == 0.0 and sim_time < TEST_DURATION:
                for _ in range(SUBSTEPS):
                    next_time = sim_time + DT
                    robot_q, phase = robot_coordinates(next_time)
                    q[:12] = robot_q
                    qd[:12] = (robot_q - previous_robot_q) / DT
                    previous_robot_q = robot_q.copy()
                    model.joint_q.assign(q)
                    model.joint_qd.assign(qd)
                    newton.eval_fk(
                        model,
                        model.joint_q,
                        model.joint_qd,
                        state_0,
                        body_flag_filter=newton.BodyFlags.KINEMATIC,
                    )
                    state_0.clear_forces()
                    collision.collide(state_0, contacts)
                    solver.step(state_0, state_1, control, contacts, DT)
                    state_0, state_1 = state_1, state_0
                    sim_time = next_time

            poses = state_0.body_q.numpy()
            center_z = float(poses[strip_links, 2].mean())
            grasp_z = float(poses[grip_links, 2].mean())
            maximum_z = max(maximum_z, center_z)
            contact_count = int(contacts.rigid_contact_count.numpy()[0])
            current_q, current_phase = robot_coordinates(sim_time)
            if remaining > 0.0:
                heading = f"STARTING IN {remaining:.1f} s"
            elif sim_time < TEST_DURATION:
                heading = current_phase
            else:
                heading = "COMPLETE"
            status.content = (
                f"### {heading}\n"
                f"- Simulation time: **{sim_time:.2f} s**\n"
                f"- Lift duration: **{LIFT_DURATION:.2f} s**\n"
                f"- Lift hold: **{LIFT_HOLD_DURATION:.2f} s**\n"
                f"- Dance duration: **{DANCE_DURATION if DANCE_MODE == 'dance' else 0.0:.2f} s**\n"
                f"- Shoulder sweep: **±{DANCE_SHOULDER_AMPLITUDE if DANCE_MODE == 'dance' else 0.0:.2f} rad**\n"
                f"- Wrist twist: **±{DANCE_WRIST_AMPLITUDE if DANCE_MODE == 'dance' else 0.0:.2f} rad**\n"
                f"- Gripper leader: **{current_q[6]:.3f} rad**\n"
                f"- Strip center z: **{center_z:.3f} m**\n"
                f"- Grasp region z: **{grasp_z:.3f} m**\n"
                f"- Grasp-region rise: **{grasp_z - initial_grasp_z:.3f} m**\n"
                f"- Maximum lift: **{maximum_z - initial_z:.3f} m**\n"
                f"- Contact candidates: **{contact_count}**\n"
                f"- Attachment constraint: **none**"
            )
            viewer.begin_frame(sim_time)
            viewer.log_state(state_0)
            viewer.end_frame()

            if sim_time >= TEST_DURATION and not result_printed:
                print(
                    f"GRASP_VIEWER_COMPLETE maximum_lift_m={maximum_z-initial_z:.4f} "
                    f"final_center_z_m={center_z:.4f}",
                    flush=True,
                )
                result_printed = True
            time.sleep(0.001)
    finally:
        viewer.close()


if __name__ == "__main__":
    main()
